"""
Generate `baseline.json`: the oracle's *non-private* aggregates for the golden queries.

The engine's exact executor (Scan -> Filter -> Aggregate/GroupBy, no bounding, no clamping,
no noise) is checked against these. They come from the oracle's own `apply_filters` and
`true_aggregate`, not from a second implementation in this file.

Reads the existing `queries.json` / `dataset.json` and changes neither. Regenerate with:

    cd oracle && uv run python tests/golden/generate_baseline.py

NULL charges count as 0 and AVG divides by the row count, matching the DP pipeline
(`SPEC.md` §4.3), so the baseline and a private answer differ only by noise and bounding.
"""
from __future__ import annotations

import json
from pathlib import Path

from privguard_oracle.dp import apply_filters, true_aggregate
from privguard_oracle.spec import ColumnPolicy, QuerySpec

HERE = Path(__file__).parent

# Wide enough that clamping never changes a value: the baseline is the unclamped truth.
UNBOUNDED = ColumnPolicy("laplace", -1e18, 1e18)


def _spec(q: dict) -> QuerySpec:
    return QuerySpec(
        agg=q["agg"],
        column=q["column"],
        filters=tuple((c, o, v) for c, o, v in q["filters"]),
        group_by=q["group_by"],
    )


def baseline_rows(q: dict, rows: list[dict]) -> list[dict]:
    spec = _spec(q)
    agg = true_aggregate(apply_filters(rows, spec.filters), spec, UNBOUNDED)

    def value(entry: dict):
        if spec.agg == "COUNT":
            return entry["n"]
        if spec.agg == "SUM":
            return entry["total"]
        return entry["total"] / entry["n"] if entry["n"] else 0.0

    if spec.group_by is None:
        return [{"value": value(agg)}]
    return [{spec.group_by: g[spec.group_by], "value": value(g)} for g in agg]


def build(rows: list[dict], queries: dict) -> dict:
    return {
        "version": 1,
        "note": "Generated by generate_baseline.py from the oracle. Do not hand-edit.",
        "queries": [
            {"id": q["id"], "rows": baseline_rows(q, rows)} for q in queries["queries"]
        ],
    }


def main() -> None:
    rows = json.loads((HERE / "dataset.json").read_text(encoding="utf-8"))
    queries = json.loads((HERE / "queries.json").read_text(encoding="utf-8"))
    out = build(rows, queries)
    with open(HERE / "baseline.json", "w", encoding="utf-8", newline="\n") as f:
        json.dump(out, f, indent=1)
        f.write("\n")
    print(f"wrote {len(out['queries'])} baseline answers to {HERE / 'baseline.json'}")


if __name__ == "__main__":
    main()
