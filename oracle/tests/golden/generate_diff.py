"""
Generate `diff_queries.json`: 1000 random queries for the engine-vs-oracle differential test.

Same entry format as `queries.json` (so the Rust side reuses its fixture reader), but the
queries come from a seeded random generator instead of a hand-written list. Every query is
valid under SPEC section 3; the point is breadth: all aggregates, all operators, 0-3 filters,
empty and tiny result sets, group-by with and without partition suppression, tight and wide
clamps and bounds, a spread of rho and principals (so every query gets its own noise seed).

Regenerate with:  cd oracle && uv run python tests/golden/generate_diff.py
`test_golden_diff.py` fails on any unannounced change to the answers.
"""
from __future__ import annotations

import importlib.util
import json
import random
from pathlib import Path

from privguard_oracle.mechanisms import derive_seed

HERE = Path(__file__).parent
N_QUERIES = 1000
RNG_SEED = 20261021

_spec = importlib.util.spec_from_file_location("golden_generate", HERE / "generate.py")
base = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(base)

WIDE_POLICY = {"mechanism": "laplace", "lower_clamp": 0.0, "upper_clamp": 500.0}
NEG_POLICY = {"mechanism": "laplace", "lower_clamp": -200.0, "upper_clamp": 2000.0}
COLUMN_POLICIES = [base.CHARGE_POLICY, base.TIGHT_POLICY, WIDE_POLICY, NEG_POLICY]
TABLE_POLICIES = [
    base.DEFAULT_TABLE,
    base.TIGHT_TABLE,
    {"max_rows_per_unit": 1, "max_groups_per_unit": 1},
    {"max_rows_per_unit": 10, "max_groups_per_unit": 4},
]
RHOS = [0.02, 0.1, 0.25, 0.5, 1.0, 2.0, 4.0]
ADMISSION = ["ELECTIVE", "EMERGENCY", "URGENT", "TRAUMA", "NONE"]
OPS = ["exact", "ne", "gt", "gte", "lt", "lte"]


def _filter(rng: random.Random, column: str) -> list:
    if column == "admission_type":
        return [column, rng.choice(["exact", "ne"]), rng.choice(ADMISSION)]
    if column == "dept_id":
        return [column, rng.choice(OPS), rng.randint(0, 5)]
    if column == "total_charge":
        op = rng.choice(["gt", "gte", "lt", "lte"])
        return [column, op, round(rng.uniform(-50.0, 1600.0), 1)]
    op = rng.choice(["gte", "lt"])
    month, day = rng.randint(1, 12), rng.randint(1, 28)
    return [column, op, f"2024-{month:02d}-{day:02d} 00:00:00"]


def build_diff_queries(rows: list[dict]) -> dict:
    rng = random.Random(RNG_SEED)
    out = []
    for i in range(N_QUERIES):
        agg = rng.choice(["COUNT", "SUM", "AVG"])
        columns = rng.sample(
            ["admission_type", "dept_id", "total_charge", "admit_ts", "discharge_ts"],
            rng.randint(0, 3),
        )
        group_by = None
        if agg != "AVG" and rng.random() < 0.4:
            group_by = rng.choice(["admission_type", "dept_id"])
        q = {
            "id": f"diff_{i:04d}",
            "agg": agg,
            "column": None if agg == "COUNT" else "total_charge",
            "filters": [_filter(rng, c) for c in columns],
            "group_by": group_by,
            "table_policy": rng.choice(TABLE_POLICIES),
            "column_policy": None if agg == "COUNT" else rng.choice(COLUMN_POLICIES),
            "rho": rng.choice(RHOS),
            "delta": base.DELTA,
            "delta_partition": base.DELTA_PARTITION,
            "server_secret_hex": base.SERVER_SECRET.hex(),
            "principal_id": rng.randint(1, 50),
            "salt_hex": base.SALT.hex(),
        }
        spec = base._spec(q)
        q["canonical"] = spec.canonical()
        q["fingerprint_hex"] = spec.fingerprint_hex()
        q["seed_hex"] = derive_seed(
            base.SERVER_SECRET, spec.ast_hash(), q["principal_id"], base.SALT
        ).hex()
        q["expected"] = base.run_query(q, rows)
        out.append(q)
    return {
        "version": 1,
        "note": "Generated by generate_diff.py from the Python oracle. Do not hand-edit.",
        "dataset": "dataset.json",
        "queries": out,
    }


def main() -> None:
    rows = json.loads((HERE / "dataset.json").read_text(encoding="utf-8"))
    doc = build_diff_queries(rows)
    with open(HERE / "diff_queries.json", "w", encoding="utf-8", newline="\n") as f:
        json.dump(doc, f, separators=(",", ":"))
        f.write("\n")
    print(f"wrote {len(doc['queries'])} queries to {HERE / 'diff_queries.json'}")


if __name__ == "__main__":
    main()
